package com.lab.repository.db;

import com.lab.domain.Entity;
import com.lab.exceptions.RepositoryException;
import com.lab.repository.Repository;
import com.lab.validator.Validator;

import java.sql.*;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * Abstract base class for the JDBC database repositories (Template Method).
 * It implements every {@link Repository} operation once: it opens the connection, prepares the
 * statement, executes it, reads the result and wraps any {@link SQLException} into a
 * {@link RepositoryException}. The subclasses only provide the SQL text and the conversion
 * between table rows and entities
 *
 * @param <ID> the type of the entity's identifier
 * @param <E>  the type of the entity, which must extend {@link Entity}
 */
public abstract class AbstractDBRepository<ID, E extends Entity<ID>> implements Repository<ID, E> {
    protected final Validator<E> validator;
    private final String url;
    private final String user;
    private final String password;

    public AbstractDBRepository(Validator<E> validator, String url, String user, String password) {
        this.validator = validator;
        this.url = url;
        this.user = user;
        this.password = password;
    }

    /**
     * Returns the SQL that selects all rows of the table
     *
     * @return the SELECT statement for all entities
     */
    protected abstract String selectAllSql();

    /**
     * Returns the SQL that selects one row by its id
     *
     * @return the SELECT statement, with a {@code ?} placeholder for each id column
     */
    protected abstract String selectOneSql();

    /**
     * Returns the SQL that deletes one row by its id.
     *
     * @return the DELETE statement, with a {@code ?} placeholder for each id column
     */
    protected abstract String deleteSql();

    /**
     * Returns the SQL that inserts a new row
     *
     * @return the INSERT statement, with a {@code ?} placeholder for each inserted value
     */
    protected abstract String insertSql();


    /**
     * Returns the SQL that changes an existing row, found by its id
     *
     * @return the UPDATE statement, with {@code ?} placeholders for the new values and for the id
     */
    protected abstract String updateSql();

    /**
     * Converts the current row of a result set into an entity
     *
     * @param resultSet the result set, positioned on a row
     * @return the entity built from that row
     * @throws SQLException if a column cannot be read
     */
    protected abstract E extractEntity(ResultSet resultSet) throws SQLException;


    /**
     * Fills the id placeholders of {@link #selectOneSql()} and {@link #deleteSql()}
     *
     * @param preparedStatement the statement whose parameters are set
     * @param id                the identifier to bind
     * @throws SQLException if a parameter cannot be set
     */
    protected abstract void setIdParameters(PreparedStatement preparedStatement, ID id) throws SQLException;


    /**
     * Fills the placeholders of {@link #insertSql()} with the values of the entity
     *
     * @param preparedStatement the statement whose parameters are set
     * @param entity            the entity whose values are inserted
     * @throws SQLException if a parameter cannot be set
     */
    protected abstract void setInsertParameters(PreparedStatement preparedStatement, E entity) throws SQLException;

    /**
     * Fills the placeholders of {@link #updateSql()} with the new values and the id of the entity
     *
     * @param preparedStatement the statement whose parameters are set
     * @param entity            the entity with the new values and its id
     * @throws SQLException if a parameter cannot be set
     */
    protected abstract void setUpdateParameters(PreparedStatement preparedStatement, E entity) throws SQLException;

    /**
     * Opens a new connection to the database with the parameters received from the factory
     *
     * @return a new connection; the caller must close it
     * @throws SQLException if the database cannot be reached or the credentials are wrong
     */
    protected Connection getConnection() throws SQLException {
        return DriverManager.getConnection(url, user, password);
    }

    /**
     * Copies the identifier generated by the database onto the entity that was just saved.
     * The default implementation does nothing, for entities whose id is not generated;
     * repositories of entities with a generated id override it
     *
     * @param resultSet the generated keys, positioned on the inserted row
     * @param entity    the entity that was just saved
     * @throws SQLException if the generated key cannot be read
     */
    protected void readGeneratedIds(ResultSet resultSet, E entity) throws SQLException {

    }

    private static void requireNonNull(String what, Object object) {
        if (object == null) {
            throw new IllegalArgumentException(what + " must not be null");
        }
    }

    @Override
    public Iterable<E> findAll() {
        try (Connection connection = getConnection();
             PreparedStatement statement = connection.prepareStatement(selectAllSql());
             ResultSet resultSet = statement.executeQuery()
        ) {
            List<E> entities = new ArrayList<>();
            while (resultSet.next()) {
                entities.add(extractEntity(resultSet));
            }
            return entities;
        } catch (SQLException e) {
            throw new RepositoryException("Error while reading from the db " + e.getMessage(), e);
        }
    }


    @Override
    public Optional<E> findOne(ID id) {
        requireNonNull("Id", id);
        try (Connection connection = getConnection();
             PreparedStatement preparedStatement = connection.prepareStatement(selectOneSql())) {
            setIdParameters(preparedStatement, id);
            try (ResultSet resultSet = preparedStatement.executeQuery()) {
                return resultSet.next() ? Optional.of(extractEntity(resultSet)) : Optional.empty();
            }

        } catch (SQLException e) {
            throw new RepositoryException("Error while reading from the db " + e.getMessage(), e);
        }
    }

    @Override
    public Optional<E> delete(ID id) {
        Optional<E> existing = findOne(id);
        if (existing.isEmpty()) {
            return existing;
        }
        try (Connection connection = getConnection();
             PreparedStatement preparedStatement = connection.prepareStatement(deleteSql())) {
            setIdParameters(preparedStatement, id);
            preparedStatement.executeUpdate();
        } catch (SQLException e) {
            throw new RepositoryException("Error while deleting from the db " + e.getMessage(), e);
        }
        return existing;
    }

    @Override
    public Optional<E> save(E entity) {
        requireNonNull("Entity", entity);
        validator.validate(entity);
        try (Connection connection = getConnection();
             PreparedStatement preparedStatement = connection.prepareStatement(insertSql(), Statement.RETURN_GENERATED_KEYS)) {
            setInsertParameters(preparedStatement, entity);
            preparedStatement.executeUpdate();
            try (ResultSet resultSet = preparedStatement.getGeneratedKeys()) {
                if (resultSet.next()) {
                    readGeneratedIds(resultSet, entity);
                }
            }
        } catch (SQLException e) {
            if ("23505".equals(e.getSQLState())) {
                return Optional.of(entity);
            }
            throw new RepositoryException("Error while inserting in the db " + e.getMessage(), e);
        }
        return Optional.empty();
    }

    @Override
    public Optional<E> update(E entity) {
        requireNonNull("Entity", entity);
        requireNonNull("Id ", entity.getId());
        validator.validate(entity);
        try (Connection connection = getConnection();
             PreparedStatement preparedStatement = connection.prepareStatement(updateSql())) {
            setUpdateParameters(preparedStatement, entity);
            int changedRows = preparedStatement.executeUpdate();
            return changedRows != 0 ? Optional.empty() : Optional.of(entity);
        } catch (SQLException e) {
            throw new RepositoryException("Error while updating the db " + e.getMessage(), e);
        }
    }
}
