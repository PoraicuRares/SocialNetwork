package com.lab.service;

import com.lab.domain.User;
import com.lab.exceptions.EmptyListException;
import com.lab.exceptions.RepositoryException;
import com.lab.exceptions.ServiceException;
import com.lab.exceptions.ValidationException;
import com.lab.repository.PagingRepository;
import com.lab.util.observer.AbstractObservable;
import com.lab.util.paging.Page;
import com.lab.util.paging.Pageable;

import java.util.Comparator;
import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/**
 * Service class responsible for managing user-related operations
 */
public class UserService extends AbstractObservable {
    private final PagingRepository<Long, User> userRepository;

    public UserService(PagingRepository<Long, User> userRepository) {
        this.userRepository = userRepository;
    }


    /**
     * Adds a new user to the network. The user's id is generated by the storage
     *
     * @param user the user to be added, without an id
     * @return the saved user, with the generated id set
     * @throws ValidationException if the user attributes are invalid
     * @throws RepositoryException if the user could not be saved
     */
    public User add(User user) {
        userRepository.save(user)
                .ifPresent(existing -> {
                    throw new RepositoryException("A user with id " + existing.getId() + " already exists");
                });
        notifyObservers();
        return user;
    }

    /**
     * Changes the name of an existing user
     *
     * @param id        the identifier of the user
     * @param firstName the new first name
     * @param lastName  the new last name
     * @return the updated user
     * @throws ValidationException if the new names are invalid
     * @throws ServiceException    if there is no user with the given id
     */
    public User update(Long id, String firstName, String lastName) {
        User user = new User(id, firstName, lastName);
        userRepository.update(user)
                .ifPresent(missing -> {
                    throw new ServiceException("There is no user with id " + missing.getId());
                });
        notifyObservers();
        return user;
    }

    /**
     * Removes a user from the network based on their id
     *
     * @param id the identifier of the user to be removed
     * @return the removed user
     * @throws ServiceException if there is no user with the given id
     */
    public User remove(Long id) {
        User removed = userRepository.delete(id)
                .orElseThrow(() -> new ServiceException("There is no user with id " + id));
        notifyObservers();
        return removed;
    }

    /**
     * Finds a user by their ID
     *
     * @param id the identifier of the user to search for
     * @return the User if found, or null otherwise
     */
    public Optional<User> findOne(Long id) {
        return userRepository.findOne(id);
    }

    /**
     * Retrieves all users currently registered in the network, sorted by id
     *
     * @return a list containing all users, sorted by id
     * @throws EmptyListException if there are no users in the network
     */
    public List<User> findAll() {
        List<User> users = userRepository.stream()
                .sorted(Comparator.comparing(User::getId))
                .collect(Collectors.toList());
        if (users.isEmpty()) {
            throw new EmptyListException("There are no users added");
        }
        return users;
    }

    /**
     * Retrieves the users that satisfy the given condition.
     * Unlike {@link #findAll()}, it does not throw if the result is empty.
     *
     * @param filter the condition a user must satisfy to be included
     * @return a list with the matching users, possibly empty
     */
    public List<User> findAll(Predicate<User> filter) {
        return userRepository.findAll(filter);
    }

    /**
     * Returns a new stream over all users, for further processing by other services.
     * Unlike {@link #findAll()}, it does not throw if there are no users.
     *
     * @return a new stream of all users, possibly empty; it can be consumed only once
     */
    public Stream<User> stream() {
        return userRepository.stream();
    }

    /**
     * Returns one page of users, sorted by id
     *
     * @param pageNumber the index of the page, starting from 0
     * @param pageSize   the number of users on a page
     * @return the users on the page and the total number of users; an empty page if it is after the last one
     * @throws IllegalArgumentException if {@code pageNumber} is negative or {@code pageSize} is not positive
     * @throws RepositoryException      if the storage cannot be accessed
     */
    public Page<User> findAllOnPage(int pageNumber, int pageSize) {
        if (pageNumber < 0 || pageSize <= 0) {
            throw new IllegalArgumentException("Page number or size invalid");
        }
        return userRepository.findAllOnPage(new Pageable(pageNumber, pageSize));
    }
}
